USE NVPhotos;
GO

CREATE TABLE Categories (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(100) NOT NULL,
  Slug NVARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE Services (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Title NVARCHAR(200) NOT NULL,
  Description NVARCHAR(MAX),
  Price DECIMAL(10,2) NOT NULL,
  PriceUnit NVARCHAR(50) DEFAULT 'рублей',
  ImageUrl NVARCHAR(500),
  CategoryId INT FOREIGN KEY REFERENCES Categories(Id),
  IsPopular BIT DEFAULT 0,
  IsActive BIT DEFAULT 1,
  SortOrder INT DEFAULT 0,
  CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE Portfolio (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Title NVARCHAR(200),
  ImageUrl NVARCHAR(500) NOT NULL,
  CategoryId INT FOREIGN KEY REFERENCES Categories(Id),
  SortOrder INT DEFAULT 0,
  CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE Achievements (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Title NVARCHAR(200) NOT NULL,
  Description NVARCHAR(MAX),
  ImageUrl NVARCHAR(500),
  Year INT,
  SortOrder INT DEFAULT 0
);

CREATE TABLE Reviews (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  AuthorName NVARCHAR(200) NOT NULL,
  ReviewText NVARCHAR(MAX) NOT NULL,
  Rating INT CHECK (Rating BETWEEN 1 AND 5),
  IsPublished BIT DEFAULT 0,
  CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE Promocodes (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Code NVARCHAR(50) UNIQUE NOT NULL,
  DiscountPercent INT NULL,
  DiscountAmount DECIMAL(10,2) NULL,
  ExpiresAt DATETIME NULL,
  UsageLimit INT NULL,
  UsedCount INT DEFAULT 0,
  IsActive BIT DEFAULT 1
);

CREATE TABLE Orders (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  CustomerName NVARCHAR(200) NOT NULL,
  Phone NVARCHAR(50) NOT NULL,
  ShootTime DATETIME NOT NULL,
  Comment NVARCHAR(MAX),
  Total DECIMAL(10,2) NOT NULL,
  PromocodeId INT NULL FOREIGN KEY REFERENCES Promocodes(Id),
  Status NVARCHAR(50) DEFAULT 'Новый',
  CreatedAt DATETIME DEFAULT GETDATE()
);

CREATE TABLE OrderItems (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  OrderId INT NOT NULL FOREIGN KEY REFERENCES Orders(Id) ON DELETE CASCADE,
  ServiceId INT NOT NULL FOREIGN KEY REFERENCES Services(Id),
  Quantity INT DEFAULT 1,
  Price DECIMAL(10,2) NOT NULL
);

CREATE TABLE Admins (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Login NVARCHAR(100) UNIQUE NOT NULL,
  PasswordHash NVARCHAR(255) NOT NULL,
  CreatedAt DATETIME DEFAULT GETDATE()
);
GO